/* ============================================================
   翻訳の取り出し
   ============================================================ */
function setLang(code){
  if (!UI_TEXT[code]) return;
  LANG = code;
  try{ localStorage.setItem(LANG_KEY, code); }catch(e){}
  document.documentElement.setAttribute('lang', code === 'hira' ? 'ja' : code);
}
function loadLang(){
  try{ return localStorage.getItem(LANG_KEY); }catch(e){ return null; }
}

// t('feed.total', {g:'120g'}) のように差し込みできる。
function t(key, vars){
  const table = UI_TEXT[LANG] || UI_TEXT.ja;
  let s = table[key];
  if (s === undefined) s = UI_TEXT.ja[key];
  if (s === undefined) return key;
  if (vars){
    Object.keys(vars).forEach(function(k){
      s = s.split('{' + k + '}').join(vars[k]);
    });
  }
  return s;
}
